#ifndef WIN_TERMUX_SESSION_H
#define WIN_TERMUX_SESSION_H

#include "common.h"

/* ---------------------------------------------------------------------------
 * v2.3.0：会话快照（`[general] session = on`，行为开关页第 6 行）。
 *
 * 存的是什么：每个标签页的分屏布局（树 + 每刀的比例 + 当时聚焦在哪个窗格）与
 * 每个窗格「已经滚出屏幕的历史 + 当前可见区」的【文本 + ANSI】（v2.3.1 起带颜色）。
 * 不是常驻进程、也不是断点续跑：正在跑的 shell / vim / ssh 不会活过退出，恢复出来
 * 的那一屏顶部会写一行说明，免得把旧文本误当成还在动的会话。真正的「关掉窗口进程
 * 不死」需要一套宿主 <-> 后台 worker 的通道（本仓库现在一个 socket 都没有），另开
 * 版本做；这里先把「终端内容别一关就没了」这件小事做完。
 *
 * 写盘的时机（v2.3.1）：干净退出（Ctrl+B d / 每个 shell 都 exit）走 session_save()；
 * 「进程可能马上就没了」的那几条路 —— Windows 的 CTRL_CLOSE/LOGOFF/SHUTDOWN、POSIX 的
 * SIGTERM/SIGHUP —— 走 session_flush_now(1)，因为等不到主循环退回来看退出钩子。两条
 * 路合起来仍是【一次写盘】：flush 会记下「这次退出已存过」，钩子那一次直接跳过。
 * SIGKILL / 崩溃仍然没有快照可谈。
 *
 * 文件格式（UTF-8，一行一条记录，行首一个字母 + 一个空格；坏档一律当「没有快照」处理）：
 *   s <版本>           版本。缺这一行 / 版本认不出 ⇒ 整档不认。
 *                      1 = 纯文本；2 = v2.3.1 起带 ANSI（见下）
 *   u <epoch>          写入时间（秒）。只给人在文件里看，界面不显示它
 *   T <color> <tree>   一个新标签页：锚点窗格的标签色 + 分屏树
 *   P <focus>          上一个 T 的下一个叶子窗格（按树的前序，与 tree 里的 p 一一对应）
 *                      focus=1 ⇒ 当时聚焦的就是这个窗格
 *   D <文本>            属于上一个 P 的一条【逻辑行】（软换行折下来的续行已并回来）
 *
 * v2.3.1：D 记录里带【终端程序自己发的 ANSI】（SGR 颜色 / 下划线 / 真彩），否则恢复出来
 * 的是一片素色。文件是一行一条记录 ⇒ ESC 写成 `\e`、反斜杠写成 `\\`；v1 的老档没有
 * 这套转义，读回来按原文对待（不然用户路径里的 `C:\e` 会被当成转义符）。
 * 刻意只存索引色（真彩仅当程序本来就用真彩时）：走 render.c 的 emit_attr16 会把 16 色
 * 换成 [theme] pane_* 的真彩，那样存进档里就换不了主题了。默认属性一格都不发。
 *
 * 树语法（前缀式，无空格）：p = 叶子；v<5..95><A><B> = 左右分（竖线），
 * h<5..95><A><B> = 上下分（横线），数字是 A 侧占比，A/B 是两个子树。
 * ------------------------------------------------------------------------- */

/* 把「此刻还活着」的窗格历史 + 布局排成一份快照留在内存里。为什么要有这一步：窗格的
 * ScreenBuffer 是在 close_pane() 里 screen_free() 掉的 ⇒ 等主循环退出、走到退出钩子时
 * 历史早没了（实测 v2.3.0 第一版就是这么把快照存成空的）。所以 pane.c 在两处调用它：
 * pane_mark_dead() 开头（紧接着就要改分屏树）与 close_pane() 开头（紧接着就要 free 屏）。
 * 多次采集只保留「最富」的一份：往后每次窗格只会更少。session = off 时直接返回。 */
void session_note_now(void);

/* 退出前调用（main 里 handle_input() 之后、关窗格的循环之前）：把内存里那份快照落盘。
 * 返回 1 = 写了文件；0 = 没写（开关关着 / 没有可存的终端窗格 / 文件打不开）。 */
int session_save(void);

/* v2.3.1：「进程可能马上就没了」时的存盘。Windows 的控制台关闭事件（点 X、注销、关机）
 * 在处理器返回后立刻终止进程，主循环那一句 session_save() 到不了 ⇒ v2.3.0 里按 X 关
 * 窗口就没有下次可恢复（用户报的「没有成功恢复」）。POSIX 的 SIGTERM/SIGHUP 也走这里。
 *   for_exit_path = 1 ⇒ 顺带记下「这次退出已存过」，session_save() 不再写第二遍
 *                       （「退出只写一次盘」这条口径不变）；
 *   for_exit_path = 0 ⇒ 只是立刻存一份，进程继续跑（POSIX 的 SIGUSR1 = 手动存盘）。
 * 内部拿锁只试有限次（≈400ms）就放弃采集、直接用已有的那份落盘：死等等于把退出挂在
 * 别的线程持有的锁上。返回 1 = 写了文件。 */
int session_flush_now(int for_exit_path);

/* v2.3.4：把挂起的快照灌进屏（排在窗格第一帧输出之后）。pane.c 的读路径在收到第一帧时调
 * 单个窗格那支；session_save()/session_flush_now() 前调 all 那支兜底。 */
void session_pump_pending(int pane_idx);
void session_pump_pending_all(void);
void session_drop_pending(int pane_idx);   /* 关窗格时丢弃未落地的挂起块 */

/* 启动时调用（第一个窗格建好之后、首次渲染之前）。返回恢复出的标签页数；
 * 0 = 没有快照或版本/格式不认 ⇒ 一切照旧启动，绝不让启动失败。 */
int session_restore(void);

#endif /* WIN_TERMUX_SESSION_H */
